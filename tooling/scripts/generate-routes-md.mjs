#!/usr/bin/env node
/**
 * Generates a compact markdown list of routes from the FastAPI OpenAPI export.
 *
 * Usage:
 *   node tooling/scripts/generate-routes-md.mjs
 *   node tooling/scripts/generate-routes-md.mjs --tag Health
 *   node tooling/scripts/generate-routes-md.mjs --prefix /api/v1/ --out docs/api-routes.md
 *
 * Only paths are listed (no schemas), grouped by OpenAPI tag.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "../..");

const HTTP_METHODS = ["get", "post", "put", "patch", "delete", "head", "options"];

function parseArgs(argv) {
  const args = {
    openapi: path.join(rootDir, "apps/api/openapi.json"),
    out: path.join(rootDir, "docs/api-routes.md"),
    prefix: "/api/v1/",
    tag: null,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--openapi") args.openapi = path.resolve(argv[++i]);
    else if (arg === "--out") args.out = path.resolve(argv[++i]);
    else if (arg === "--prefix") args.prefix = argv[++i];
    else if (arg === "--tag") args.tag = argv[++i];
    else if (arg === "--help" || arg === "-h") {
      console.log(
        [
          "Usage: node tooling/scripts/generate-routes-md.mjs [options]",
          "  --openapi <path>  OpenAPI JSON to read (default: apps/api/openapi.json)",
          "  --out <path>      Markdown file to write (default: docs/api-routes.md)",
          "  --prefix <path>   Only include paths starting with this (default: /api/v1/)",
          "  --tag <name>      Only include routes with this tag (case-insensitive)",
        ].join("\n")
      );
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return args;
}

function buildRoutes(spec, { prefix, tag }) {
  const wantedTag = tag ? tag.toLowerCase() : null;
  const groups = new Map();

  for (const [routePath, operations] of Object.entries(spec.paths ?? {})) {
    if (prefix && !routePath.startsWith(prefix)) continue;

    for (const method of HTTP_METHODS) {
      const operation = operations[method];
      if (!operation) continue;

      const tags = operation.tags?.length ? operation.tags : ["Untagged"];
      if (wantedTag && !tags.some((t) => t.toLowerCase() === wantedTag)) continue;

      const groupName = tags[0];
      if (!groups.has(groupName)) groups.set(groupName, []);
      groups.get(groupName).push({
        method: method.toUpperCase(),
        path: routePath,
        summary: operation.summary ?? "",
      });
    }
  }

  return groups;
}

function renderMarkdown(spec, groups, { prefix, tag, openapiPath }) {
  const title = spec.info?.title ?? "API";
  const version = spec.info?.version ?? "unknown";
  const total = [...groups.values()].reduce((sum, list) => sum + list.length, 0);

  const lines = [
    `# ${title} — Routes`,
    "",
    `Version: \`${version}\`  `,
    `Source: \`${path.relative(rootDir, openapiPath).replaceAll("\\", "/")}\`  `,
    `Filter: ${prefix ? `paths starting with \`${prefix}\`` : "all paths"}${
      tag ? `, tag \`${tag}\`` : ""
    }  `,
    `Routes: ${total}`,
    "",
    "_Generated by `pnpm routes:md` (tooling/scripts/generate-routes-md.mjs). Do not edit by hand._",
    "",
  ];

  for (const [groupName, routes] of groups) {
    lines.push(`## ${groupName}`, "");
    for (const route of routes) {
      const suffix = route.summary ? ` — ${route.summary}` : "";
      lines.push(`- \`${route.method} ${route.path}\`${suffix}`);
    }
    lines.push("");
  }

  if (total === 0) {
    lines.push("_No routes matched the filter._", "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function main() {
  const options = parseArgs(process.argv.slice(2));

  if (!fs.existsSync(options.openapi)) {
    throw new Error(`OpenAPI file not found: ${options.openapi}`);
  }

  const spec = JSON.parse(fs.readFileSync(options.openapi, "utf8"));
  const groups = buildRoutes(spec, options);
  const markdown = renderMarkdown(spec, groups, {
    prefix: options.prefix,
    tag: options.tag,
    openapiPath: options.openapi,
  });

  fs.mkdirSync(path.dirname(options.out), { recursive: true });
  fs.writeFileSync(options.out, markdown, "utf8");

  const total = [...groups.values()].reduce((sum, list) => sum + list.length, 0);
  console.log(
    `✅ [routes:md] Wrote ${total} route(s) to ${path.relative(rootDir, options.out)}`
  );
}

try {
  main();
} catch (error) {
  console.error(`❌ [routes:md] ${error.message}`);
  process.exit(1);
}
